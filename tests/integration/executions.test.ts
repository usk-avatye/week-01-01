import assert from 'node:assert/strict';
import test from 'node:test';
import type { CampaignDto, Page } from '../../src/contracts/campaigns.js';
import type { ExecutionDto } from '../../src/contracts/executions.js';
import { createHttpFixture } from '../support/http.js';
import { advertiser } from '../support/advertiser.js';
import { execute, prepare, setupCampaign } from '../support/campaign.js';
test('concurrent preparations issue distinct numbers without spending while paused', async (t) => {
    const f = await createHttpFixture();
    t.after(() => f.close());
    const a = await advertiser(f);
    const { path } = await setupCampaign(a, 10000, false);
    const records = await Promise.all(Array.from({ length: 20 }, () => prepare(a, path)));
    assert.equal(new Set(records.map(record => record.requestId)).size, 20);
    assert.ok(records.every(record => record.status === 'PREPARED' && record.approvedAmount === 0));
    assert.equal((await a.request<CampaignDto>('GET', path)).body.spentAmount, 0);
    assert.equal((await a.request<Page<ExecutionDto>>('GET', path + '/executions')).body.items.length, 0);
});
test('twenty distinct thousand-won spends approve exactly ten against ten-thousand budget', async (t) => {
    const f = await createHttpFixture();
    t.after(() => f.close());
    const a = await advertiser(f);
    const { campaign, path } = await setupCampaign(a);
    const prepared = await Promise.all(Array.from({ length: 20 }, () => prepare(a, path)));
    const results = await Promise.all(prepared.map(record => execute(a, path, record.requestId, 1000)));
    assert.ok(results.every(result => result.status === 200));
    assert.equal(results.filter(result => result.body.status === 'APPROVED').length, 10);
    assert.equal(results.filter(result => result.body.status === 'REJECTED').length, 10);
    const current = await a.request<CampaignDto>('GET', path);
    assert.equal(current.body.spentAmount, 10000);
    assert.equal(current.body.remainingBudget, 0);
    const aggregate = await f.pool.query('SELECT SUM(approved_amount) AS amount FROM executions WHERE campaign_id=$1', [campaign.id]);
    assert.equal(aggregate.rows[0].amount, '10000');
});
test('twenty transmissions of one request debit once and preserve the original result after pause', async (t) => {
    const f = await createHttpFixture();
    t.after(() => f.close());
    const a = await advertiser(f);
    const { path } = await setupCampaign(a);
    const record = await prepare(a, path);
    const results = await Promise.all(Array.from({ length: 20 }, () => execute(a, path, record.requestId, 1000)));
    assert.ok(results.every(result => result.status === 200 && result.body.status === 'APPROVED' && result.body.approvedAmount === 1000));
    for (const result of results)
        assert.deepEqual(result.body, results[0]!.body);
    assert.equal((await a.request<CampaignDto>('GET', path)).body.spentAmount, 1000);
    await a.request('PATCH', path + '/status', { status: 'PAUSED' });
    assert.deepEqual((await execute(a, path, record.requestId, 1000)).body, results[0]!.body);
    assert.equal((await execute(a, path, record.requestId, 2000)).status, 409);
    assert.equal((await a.request<Page<ExecutionDto>>('GET', path + '/executions')).body.items.length, 1);
});
test('budget rejection remains fixed after increase and only a new number receives a new decision', async (t) => {
    const f = await createHttpFixture();
    t.after(() => f.close());
    const a = await advertiser(f);
    const { path } = await setupCampaign(a, 1000);
    const record = await prepare(a, path);
    const rejected = await execute(a, path, record.requestId, 2000);
    assert.equal(rejected.body.status, 'REJECTED');
    assert.equal(rejected.body.rejectionReason, 'INSUFFICIENT_BUDGET');
    await a.request('PATCH', path + '/status', { status: 'PAUSED' });
    await a.request('PATCH', path + '/budget', { totalBudget: 5000 });
    await a.request('PATCH', path + '/status', { status: 'ACTIVE' });
    assert.deepEqual((await execute(a, path, record.requestId, 2000)).body, rejected.body);
    const next = await prepare(a, path);
    assert.equal((await execute(a, path, next.requestId, 2000)).body.status, 'APPROVED');
    assert.equal((await a.request<CampaignDto>('GET', path)).body.spentAmount, 2000);
});
