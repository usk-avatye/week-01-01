test('database failure after debit rolls back both balance and result', async (t) => {
    const f = await createHttpFixture();
    t.after(() => f.close());
    const a = await advertiser(f);
    const { path } = await setupCampaign(a);
    const record = await prepare(a, path);
    await f.pool.query(`CREATE FUNCTION fail_result() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN RAISE EXCEPTION 'test result write failure'; END $$;
    CREATE TRIGGER fail_result BEFORE UPDATE ON executions FOR EACH ROW EXECUTE FUNCTION fail_result()`);
    assert.equal((await execute(a, path, record.requestId, 1000)).status, 500);
    assert.equal((await a.request<CampaignDto>('GET', path)).body.spentAmount, 0);
    const ready = await a.request<ExecutionDto>('GET', `${path}/executions/${record.requestId}`);
    assert.equal(ready.body.status, 'PREPARED');
    assert.equal(ready.body.requestedAmount, null);
    await f.pool.query('DROP TRIGGER fail_result ON executions');
    assert.equal((await execute(a, path, record.requestId, 1000)).body.status, 'APPROVED');
});
